/** 生成已知拍点的变速示例及可编辑包，不把测试音伪称真实音乐。 @author ahui */
import { createServer } from 'vite';
import fs from 'node:fs/promises';
import { createHash, randomUUID } from 'node:crypto';
import { zipSync } from 'fflate';
const server = await createServer({
  optimizeDeps: { noDiscovery: true, entries: [] },
  server: { middlewareMode: true },
  appType: 'custom',
});
try {
  const rules = await server.ssrLoadModule('/src/games/word-beat/rules.ts'),
    exporter = await server.ssrLoadModule('/src/portable/export.ts'),
    schema = await server.ssrLoadModule('/src/shared/schemas/lesson-package.ts'),
    games = await server.ssrLoadModule('/src/platform/games.ts'),
    attribution = await server.ssrLoadModule('/src/shared/attribution.ts');
  const game = games.getGame('word-beat');
  const sr = 48000,
    seconds = 8.125,
    samples = Math.round(sr * seconds),
    wav = Buffer.alloc(44 + samples * 2);
  wav.write('RIFF');
  wav.writeUInt32LE(wav.length - 8, 4);
  wav.write('WAVEfmt ', 8);
  wav.writeUInt32LE(16, 16);
  wav.writeUInt16LE(1, 20);
  wav.writeUInt16LE(1, 22);
  wav.writeUInt32LE(sr, 24);
  wav.writeUInt32LE(sr * 2, 28);
  wav.writeUInt16LE(2, 32);
  wav.writeUInt16LE(16, 34);
  wav.write('data', 36);
  wav.writeUInt32LE(samples * 2, 40);
  // 已知120 BPM、首拍125ms，真实PCM脉冲供校准和倍率复核，不用于评价学生。
  for (let n = 0; n < samples; n++) {
    const t = n / sr,
      phase = (t - 0.125 + 0.5) % 0.5;
    wav.writeInt16LE(
      Math.round(
        t >= 0.125 && phase < 0.04
          ? Math.sin(2 * Math.PI * 880 * t) * (1 - phase / 0.04) * 18000
          : 0,
      ),
      44 + n * 2,
    );
  }
  const hash = (b) => createHash('sha256').update(b).digest('hex');
  const asset = {
    assetId: randomUUID(),
    kind: 'music',
    name: '已知120BPM测试音',
    mimeType: 'audio/wav',
    byteLength: wav.length,
    durationMs: seconds * 1000,
    sha256: hash(wav),
    dataUrl: 'data:audio/wav;base64,' + wav.toString('base64'),
  };
  const lesson = rules.createWordBeatLesson(
    ['knowledge', 'take part in'].map((english, i) => ({
      id: String(i),
      english,
      meaning: i ? '参加' : '知识',
      priority: false,
    })),
    { soundMode: 'chorus', seed: 123, name: '自主齐读 · 保音高变速校准示例（测试音）' },
  );
  Object.values(lesson.gameData.slogans).forEach((s) => (s.enabled = false));
  lesson.gameData.bpm.value = 144;
  lesson.gameData.beatEnabled = false;
  lesson.gameData.music = {
    enabled: true,
    assetId: asset.assetId,
    loop: true,
    preservePitch: true,
    syncEnabled: true,
    sync: { bpm: 120, firstBeatMs: 125, loopStartMs: 125, loopEndMs: 2125 },
  };
  rules.getEntries(lesson)[1].chorus = {
    beats: { value: 4, source: 'manual', locked: false },
    beatsPerRead: { value: 2, source: 'manual', locked: false },
  };
  lesson.revision = 1;
  lesson.preparedRevision = 1;
  const name = '单词节拍-保音高变速校准';
  await fs.writeFile(
    `examples/${name}.html`,
    await exporter.createClassroomHtml(lesson, { [asset.assetId]: asset }),
  );
  const lessonBytes = Buffer.from(JSON.stringify(schema.createPackageData(lesson, lesson)));
  const packaged = schema.packageAsset(asset);
  const manifest = schema.validatePackageManifest({
    formatVersion: 1,
    runtimeVersion: 3,
    minimumPlatformVersion: '1.0.0',
    gameId: lesson.gameId,
    sourceLessonId: lesson.id,
    generatedAt: new Date().toISOString(),
    lessonSha256: hash(lessonBytes),
    assets: [packaged],
  });
  await fs.writeFile(
    `examples/${name}.ecglesson`,
    zipSync({
      'manifest.json': Buffer.from(JSON.stringify(manifest)),
      'lesson.json': lessonBytes,
      [packaged.path]: wav,
      'attribution.txt': Buffer.from(attribution.CLASSROOM_ATTRIBUTION),
      'license.txt': Buffer.from(
        'Synthetic 120 BPM test audio generated by ahui. This editable package contains data and media, not player code. Teaching content retains its own rights. Software: GPL-3.0-only; newly exported HTML includes player source.\n\n' +
          attribution.CLASSROOM_ATTRIBUTION,
      ),
    }),
  );
  await fs.writeFile(
    'examples/validation/tempo.identity.json',
    JSON.stringify(
      {
        lessonSha256: manifest.lessonSha256,
        revisions: [{ revision: 1, layout: game.describeIdentities(lesson) }],
      },
      null,
      2,
    ),
  );
  console.log(name);
} finally {
  await server.close();
}
