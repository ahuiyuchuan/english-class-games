/**
 * 从锁定安装结果收集生产依赖的真实许可，供安装包和离线课堂文件携带。
 * 只遍历项目生产依赖及其运行依赖，不复制开发工具，不编造缺失的许可正文。
 * 执行：node scripts/prepare-notices.mjs；输出为生成文件，不应手工修改。
 * @author ahui
 */
import { readFile, readdir, realpath, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const rootPackage = join(projectDirectory, 'package.json');
const visited = new Set();
const notices = [];
const missing = [];
// 少数发行包声明许可但漏发正文。只接受已核对来源、版本及摘要的本地副本，构建不联网。
const retainedDirectory = join(projectDirectory, 'resources/licenses');
const retained = JSON.parse(
  await readFile(join(retainedDirectory, 'sources.json'), 'utf8'),
).packages;

/**
 * 沿已解析入口向上查找对应包，兼容禁止直接导出 package.json 的依赖。
 * @param {string} name 依赖的真实包名。
 * @param {string} parentPackage 调用方 package.json 的绝对路径，用于遵循 pnpm 嵌套解析。
 * @returns {Promise<string>} 已安装依赖的真实 package.json 路径。
 * @throws {Error} 必需依赖未安装或入口无法对应到其真实包时停止构建。
 */
async function locatePackage(name, parentPackage) {
  // 仅有 import 条件导出的 ESM 包没有 require 入口。沿 Node 的实际搜索路径
  // 读取包元数据，仍核对包名并解析 pnpm 链接，不靠猜测 dist 文件名。
  for (const search of createRequire(parentPackage).resolve.paths(name) ?? []) {
    const candidate = join(search, name, 'package.json');
    try {
      const metadata = JSON.parse(await readFile(candidate, 'utf8'));
      if (metadata.name === name) return realpath(candidate);
    } catch (cause) {
      if (cause.code !== 'ENOENT') throw cause;
    }
  }
  let directory = dirname(createRequire(parentPackage).resolve(name));
  while (directory !== dirname(directory)) {
    const candidate = join(directory, 'package.json');
    try {
      const metadata = JSON.parse(await readFile(candidate, 'utf8'));
      if (metadata.name === name) return realpath(candidate);
    } catch (cause) {
      if (cause.code !== 'ENOENT') throw cause;
    }
    directory = dirname(directory);
  }
  throw new Error(`无法定位生产依赖许可：${name}`);
}

/**
 * 记录每个实际安装版本一次，递归收集运行依赖；可选依赖缺席只影响该平台。
 * @param {string} packageFile 真实 package.json 绝对路径。
 * @param {boolean} include 当前包是否属于需输出许可的第三方依赖。
 * @returns {Promise<void>} 收集结果保存在本次构建内存中，不改动 node_modules。
 */
async function collect(packageFile, include = true) {
  if (visited.has(packageFile)) return;
  visited.add(packageFile);
  const metadata = JSON.parse(await readFile(packageFile, 'utf8'));
  const directory = dirname(packageFile);
  if (include) {
    const names = (await readdir(directory))
      .filter((name) => /^(?:licen[cs]e|copying|notice)(?:\.[^.]+)?$/iu.test(name))
      .sort();
    const sections = [];
    for (const name of names) {
      const contents = (await readFile(join(directory, name), 'utf8')).replace(/\r\n/gu, '\n');
      sections.push(`${name}\n${contents.trim()}\n`);
    }
    if (!names.some((name) => /^(?:licen[cs]e|copying)/iu.test(name))) {
      const retainedSource = retained[`${metadata.name}@${metadata.version}`];
      if (!retainedSource) missing.push(`${metadata.name}@${metadata.version}`);
      else {
        const bytes = await readFile(join(retainedDirectory, retainedSource.file));
        if (createHash('sha256').update(bytes).digest('hex') !== retainedSource.sha256)
          throw new Error(`保留的许可正文摘要不匹配：${metadata.name}`);
        sections.push(
          `Retained upstream license: ${retainedSource.source}\n${bytes.toString('utf8')}`,
        );
      }
    }
    notices.push({
      key: `${metadata.name}@${metadata.version}`,
      text: `${metadata.name}@${metadata.version}\nDeclared license: ${metadata.license ?? 'See license text'}\n\n${sections.join('\n')}`,
    });
  }
  const optional = metadata.optionalDependencies ?? {};
  for (const name of Object.keys({ ...metadata.dependencies, ...optional }).sort()) {
    let dependency;
    try {
      dependency = await locatePackage(name, packageFile);
    } catch (cause) {
      if (name in optional && cause.code === 'MODULE_NOT_FOUND') continue;
      throw cause;
    }
    await collect(dependency);
  }
}

await collect(rootPackage, false);
// MPL 发行包仅包含简短声明，附完整许可和精确版本的源码获取位置。
notices.push({
  key: 'SoundTouchJS MPL source offer',
  text:
    (await readFile(join(retainedDirectory, 'MPL-2.0.txt'), 'utf8')) +
    '\nSoundTouchJS 2.1.1 source: https://github.com/cutterbl/SoundTouchJS/tree/d9e39a7ddcf74c7a145bbba45856f30068c82b79\nUnmodified source is also distributed in resources/licenses/soundtouchjs-2.1.1-source/.\n',
});
if (missing.length) throw new Error(`生产依赖缺少可分发的许可正文：${missing.join(', ')}`);
notices.sort((left, right) => (left.key < right.key ? -1 : left.key > right.key ? 1 : 0));
const header = [
  'English Class Games — third-party production dependency notices',
  'Generated by scripts/prepare-notices.mjs. Maintainer: ahui.',
  'This inventory includes installed runtime dependencies; each distribution may use a subset.',
  'Original copyright and permission notices are preserved below.',
].join('\n');
await writeFile(
  join(projectDirectory, 'resources/THIRD-PARTY-NOTICES.txt'),
  `${header}\n\n${notices.map((item) => item.text).join('\n----------------------------------------\n\n')}`,
  'utf8',
);
process.stdout.write(`已收集 ${notices.length} 个生产依赖的真实许可。\n`);
