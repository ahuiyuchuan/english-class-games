/**
 * 品牌图标唯一生成入口：复用侧栏原有 Phosphor 手柄与星芒，生成 SVG 及 Windows 图标。
 * PNG/ICO 是构建产物，修改形状应修改此文件；临时平台图标只保留项目实际使用的两项。
 * @author ahui
 */
import { createHash } from 'node:crypto';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { GameController, Sparkle } from '@phosphor-icons/react';
import { mkdir, mkdtemp, writeFile, copyFile, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const config = JSON.parse(
  await readFile(new URL('../src-tauri/tauri.conf.json', import.meta.url), 'utf8'),
);
const cargo = await readFile(new URL('../src-tauri/Cargo.toml', import.meta.url), 'utf8');
const binaryName = cargo.match(/^name\s*=\s*"([^"]+)"/m)[1];
const root = fileURLToPath(new URL('../', import.meta.url));
const controller = renderToStaticMarkup(
  createElement(GameController, { size: 28, color: '#07111f' }),
);
const sparkle = renderToStaticMarkup(
  createElement(Sparkle, { size: 13, weight: 'fill', color: '#c6f45a' }),
);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 64 64">
  <defs><linearGradient id="card" x2="1" y2="1"><stop stop-color="#65e5fa"/><stop offset="1" stop-color="#82e9fa"/></linearGradient></defs>
  <g transform="rotate(-5 32 32)">
    <path d="M9 24Q9 12 21 12H53V47Q53 59 41 59H9Z" fill="#061321"/>
    <path d="M9 20Q9 8 21 8H53V43Q53 55 41 55H9Z" fill="url(#card)" stroke="#82e9fa"/>
    <g transform="translate(17 20)">${controller}</g>
    <rect x="39" y="3" width="20" height="20" rx="5" fill="#07111f"/>
    <g transform="translate(42.5 6.5)">${sparkle}</g>
  </g>
</svg>\n`;
await mkdir(join(root, 'public'), { recursive: true });
await writeFile(join(root, 'public/app-icon.svg'), svg, 'utf8');
const temporary = await mkdtemp(join(tmpdir(), 'ecg-icons-'));
try {
  const result = spawnSync(
    process.execPath,
    [
      join(root, 'node_modules/@tauri-apps/cli/tauri.js'),
      'icon',
      join(root, 'public/app-icon.svg'),
      '--output',
      temporary,
    ],
    { stdio: 'inherit' },
  );
  if (result.status !== 0) throw new Error('品牌图标生成失败，不能继续打包。');
  for (const name of ['icon.png', 'icon.ico'])
    await copyFile(join(temporary, name), join(root, 'src-tauri/icons', name));
  // A content-specific icon path bypasses stale Explorer EXE icon cache after reinstall.
  const ico = await readFile(join(temporary, 'icon.ico'));
  const iconName = `app-${createHash('sha256').update(ico).digest('hex').slice(0, 16)}.ico`;
  await mkdir(join(root, 'resources/icons'), { recursive: true });
  await writeFile(join(root, 'resources/icons', iconName), ico);
  await writeFile(
    join(root, 'src-tauri/brand-icon.nsh'),
    `; Generated by build-icons.mjs.\n!define ECG_BRAND_ICON "resources\\icons\\${iconName}"\n!define ECG_PRODUCT_NAME "${config.productName}"\n!define ECG_BINARY_NAME "${binaryName}"\n!define ECG_BUNDLE_ID "${config.identifier}"\n`,
    'utf8',
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}
